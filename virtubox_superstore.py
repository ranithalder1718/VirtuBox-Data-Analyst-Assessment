# Part 3: Calculate Business KPIs

total_sales = df["sales"].sum()
total_profit = df["profit"].sum()

profit_margin = (
    total_profit / total_sales * 100
    if total_sales != 0 else 0
)

total_orders = df["order_id"].nunique()

average_discount = df["discount"].mean() * 100

loss_records = (df["profit"] < 0).sum()

kpi_results = pd.DataFrame({
    "Metric": [
        "Total Sales",
        "Total Profit",
        "Profit Margin (%)",
        "Distinct Orders",
        "Average Discount (%)",
        "Records with Negative Profit"
    ],
    "Value": [
        total_sales,
        total_profit,
        profit_margin,
        total_orders,
        average_discount,
        loss_records
    ]
})

display(kpi_results.round(2))

print(df.columns.tolist())

category_analysis = (
    df.groupby("category")
    .agg(
        Total_Sales=("sales", "sum"),
        Total_Profit=("profit", "sum"),
        Total_Quantity=("quantity", "sum")
    )
    .reset_index()
)

category_analysis["Profit_Margin_Percent"] = (
    category_analysis["Total_Profit"]
    / category_analysis["Total_Sales"] * 100
)

display(
    category_analysis.sort_values(
        "Total_Sales",
        ascending=False
    ).round(2)
)

subcategory_analysis = (
    df.groupby("sub_category")
    .agg(
        Total_Sales=("sales", "sum"),
        Total_Profit=("profit", "sum")
    )
    .reset_index()
    .sort_values("Total_Profit")
)

display(subcategory_analysis.round(2))

region_analysis = (
    df.groupby("region")
    .agg(
        Total_Sales=("sales", "sum"),
        Total_Profit=("profit", "sum")
    )
    .reset_index()
    .sort_values("Total_Profit", ascending=False)
)

display(region_analysis.round(2))

discount_analysis = (
    df.groupby("discount")
    .agg(
        Average_Profit=("profit", "mean"),
        Total_Profit=("profit", "sum"),
        Record_Count=("profit", "count")
    )
    .reset_index()
    .sort_values("discount")
)

display(discount_analysis.round(2))

